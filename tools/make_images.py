class SVG:
    def __init__(self, w, h, title="", subtitle=""):
        self.w, self.h = w, h
        self.parts = []
        self.title = title
        self.subtitle = subtitle

    def add(self, s):
        self.parts.append(s)

    # ---------------------------------------------------------------- shapes
    def rect(self, x, y, w, h, fill="#fff", stroke="#343a40", sw=1.6, rx=6, dash=None, op=1):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" '
                 f'stroke="{stroke}" stroke-width="{sw}" opacity="{op}"{d}/>')

    def circle(self, cx, cy, r, fill="#fff", stroke="#343a40", sw=1.6):
        self.add(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>')

    def text(self, x, y, s, size=13, color="#212529", anchor="middle", weight="normal", style="normal"):
        s = (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
        self.add(f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" fill="{color}" '
                 f'text-anchor="{anchor}" font-weight="{weight}" font-style="{style}">{s}</text>')

    def lines(self, x, y, rows, size=13, lh=17, color="#212529", anchor="middle", weight="normal"):
        for i, row in enumerate(rows):
            self.text(x, y + i * lh, row, size, color, anchor, weight)

    def pipe(self, pts, color, w=5, dash=None, arrow=True):
        p = " ".join(f"{x},{y}" for x, y in pts)
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.add(f'<polyline points="{p}" fill="none" stroke="{color}" stroke-width="{w}" '
                 f'stroke-linecap="round" stroke-linejoin="round"{d}/>')
        if arrow:
            (x1, y1), (x2, y2) = pts[-2], pts[-1]
            import math
            a = math.atan2(y2 - y1, x2 - x1)
            L, Wd = 11, 5.5
            xm, ym = (x1 + x2) / 2, (y1 + y2) / 2
            p1 = (xm - L * math.cos(a - 0.45), ym - L * math.sin(a - 0.45))
            p2 = (xm - L * math.cos(a + 0.45), ym - L * math.sin(a + 0.45))
            self.add(f'<polygon points="{xm},{ym} {p1[0]:.1f},{p1[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}" fill="{color}"/>')

    def pump(self, cx, cy, color="#343a40", r=13):
        self.circle(cx, cy, r, "#fff", color, 2)
        self.add(f'<polygon points="{cx-5},{cy-6} {cx-5},{cy+6} {cx+6},{cy}" fill="{color}"/>')

    def threeway(self, cx, cy, color="#343a40", label="3"):
        self.add(f'<polygon points="{cx},{cy-11} {cx-10},{cy+7} {cx+10},{cy+7}" fill="#fff" '
                 f'stroke="{color}" stroke-width="2"/>')
        self.text(cx, cy + 4, label, 10, color, "middle", "bold")

    def sensor(self, cx, cy, tag, color="#862e9c"):
        self.rect(cx - 13, cy - 10, 26, 20, "#fff", color, 1.5, 4)
        self.text(cx, cy + 4, tag, 10, color, "middle", "bold")

    def box(self, x, y, w, h, rows, fill="#fff", stroke="#343a40", size=13, color="#212529", bold_first=True):
        self.rect(x, y, w, h, fill, stroke, 1.8, 8)
        n = len(rows)
        y0 = y + h / 2 - (n - 1) * 8.5 + 4
        for i, row in enumerate(rows):
            self.text(x + w / 2, y0 + i * 17, row, size, color, "middle",
                      "bold" if (i == 0 and bold_first) else "normal")

    def legend(self, x, y, items):
        self.rect(x - 12, y - 20, 250, 22 + 20 * len(items), "#fff", "#adb5bd", 1, 6)
        self.text(x + 110, y - 4, "ЛЕГЕНДА", 11, "#495057", "middle", "bold")
        for i, (color, label, dash) in enumerate(items):
            yy = y + 16 + i * 20
            self.add(f'<line x1="{x}" y1="{yy}" x2="{x+34}" y2="{yy}" stroke="{color}" stroke-width="5" '
                     f'stroke-linecap="round"' + (f' stroke-dasharray="{dash}"' if dash else "") + '/>')
            self.text(x + 44, yy + 4, label, 11.5, "#343a40", "start")

    def note(self, x, y, w, rows):
        self.rect(x, y, w, 24 + 15 * len(rows), "#fff9db", "#f59f00", 1.2, 6)
        for i, r in enumerate(rows):
            self.text(x + 10, y + 18 + i * 15, r, 11, "#664d03", "start")

    def render(self):
        head = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" '
            f'viewBox="0 0 {self.w} {self.h}">',
            f'<rect width="{self.w}" height="{self.h}" fill="#ffffff"/>',
            f'<text x="24" y="34" font-family="{FONT}" font-size="21" font-weight="bold" fill="#1c1d21">'
            f'{self.title}</text>',
            f'<text x="24" y="55" font-family="{FONT}" font-size="12.5" fill="#6c757d">{self.subtitle}</text>',
            f'<line x1="24" y1="64" x2="{self.w-24}" y2="64" stroke="#dee2e6" stroke-width="1.5"/>',
        ]
        foot = [
            f'<text x="{self.w-24}" y="{self.h-12}" font-family="{FONT}" font-size="10.5" fill="#868e96" '
            f'text-anchor="end">Концептуална схема – не е проект за монтаж. Всички размери и свързвания '
            f'подлежат на проверка от правоспособен проектант.</text>',
            "</svg>",
        ]
        return "\n".join(head + self.parts + foot)

    def save(self, name):
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write(self.render())
        print("written", name)


