def chart():
    import json
    R = json.load(open(os.path.join(OUT, "..", "data", "model_results.json")))
    r = next(x for x in R if x["n"] == 5 and x["v_buf"] == 800 and x["type"] == "flat")
    months = ["Яну", "Фев", "Мар", "Апр", "Май", "Юни", "Юли", "Авг", "Сеп", "Окт", "Ное", "Дек"]
    dem = r["demand_m"]
    dhw = [10.46 * d for d in (31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)]
    sol = r["yield_m"]
    used = r["used_m"]
    W, H = 1000, 470
    s = SVG(W, H, "Месечен енергиен баланс – 5 плоски колектора, буфер 800 l",
            "Отопление, БГВ, произведена и реално използвана слънчева енергия, kWh/месец")
    x0, y0, pw, ph = 70, 360, 900, 260
    maxv = 2000
    for v in range(0, maxv + 1, 400):
        y = y0 - v / maxv * ph
        s.add(f'<line x1="{x0}" y1="{y:.0f}" x2="{x0+pw}" y2="{y:.0f}" stroke="#dee2e6"/>')
        s.text(x0 - 10, y + 4, str(v), 10, "#868e96", "end")
    bw = pw / 12
    for i in range(12):
        x = x0 + i * bw + bw * 0.16
        w = bw * 0.68
        h1 = min(dem[i], maxv) / maxv * ph
        h2 = dhw[i] / maxv * ph
        s.add(f'<rect x="{x:.1f}" y="{y0-h1:.1f}" width="{w:.1f}" height="{h1:.1f}" fill="#c92a2a" opacity="0.85"/>')
        s.add(f'<rect x="{x:.1f}" y="{y0-h1-h2:.1f}" width="{w:.1f}" height="{h2:.1f}" fill="#2f9e44" opacity="0.85"/>')
        s.add(f'<rect x="{x+w*0.25:.1f}" y="{y0-used[i]/maxv*ph:.1f}" width="{w*0.5:.1f}" '
              f'height="{used[i]/maxv*ph:.1f}" fill="#1c7ed6" opacity="0.95"/>')
        s.add(f'<line x1="{x+w/2:.1f}" y1="{y0-sol[i]/maxv*ph:.1f}" x2="{x+w/2:.1f}" y2="{y0:.1f}" '
              f'stroke="#f08c00" stroke-width="2.5"/>')
        s.circle(x + w / 2, y0 - sol[i] / maxv * ph, 4.5, "#fff", "#f08c00", 2)
        s.text(x + w / 2, y0 + 16, months[i], 10.5, "#495057")
    s.add(f'<line x1="{x0}" y1="{y0}" x2="{x0+pw}" y2="{y0}" stroke="#495057" stroke-width="2"/>')

    for i, (c, t) in enumerate([("#c92a2a", "Отопление"), ("#2f9e44", "БГВ"),
                                ("#1c7ed6", "Използвано слънце"),
                                ("#f08c00", "Произведено слънце")]):
        x = 90 + i * 215
        s.add(f'<rect x="{x}" y="{400}" width="16" height="12" fill="{c}"/>')
        s.text(x + 24, 411, t, 11.5, "#343a40", "start")
    s.text(70, 442, f"Годишно: отопление {sum(dem):,.0f} kWh · БГВ {sum(dhw):,.0f} kWh · "
                    f"произведено {sum(sol):,.0f} kWh · използвано {sum(used):,.0f} kWh "
                    f"({sum(used)/(sum(dem)+sum(dhw))*100:.0f} %)".replace(",", " "),
           11, "#6c757d", "start")
    s.save("chart-monthly.svg")


